#!/usr/bin/env python3
"""Build tui/welcome/shadowFont.ts from assets/brand/ansi-shadow.flf.

ANSI Shadow is the figlet face the EVALS banner is set in; exporting the
whole face lets every headline in the welcome intro share one typographic
voice. Only A–Z, 0–9 and a few punctuation marks are emitted.
"""
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FLF = os.path.join(ROOT, "assets", "brand", "ansi-shadow.flf")
OUT = os.path.join(ROOT, "tui", "welcome", "shadowFont.ts")

lines = open(FLF, encoding="utf-8").read().split("\n")
header = lines[0].split()
hardblank = header[0][-1]
height = int(header[1]); comment_lines = int(header[5])
body = lines[1 + comment_lines:]
# figlet: characters 32..126 in order, each `height` lines, terminated by @ (last line @@)
glyphs = {}
idx = 0
for code in range(32, 127):
    rows = body[idx: idx + height]; idx += height
    clean = [re.sub(r"@+$", "", r).replace(hardblank, " ") for r in rows]
    glyphs[chr(code)] = clean
WANT = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.%:-/' "
out = {ch: glyphs[ch] for ch in WANT if ch in glyphs}
# trim: drop fully-empty trailing rows shared by all (ANSI Shadow uses 6 rows + 1 blank)
def width(g): return max(len(r) for r in g)
ts = ['/**', ' * ANSI Shadow — the figlet face the EVALS banner is set in. GENERATED by', ' * scripts/build-shadow-font.py from assets/brand/ansi-shadow.flf; do not', ' * edit by hand. Rows are equal-height per glyph; widths vary.', ' */', '', f'export const SHADOW_ROWS = {height};', '', 'export const SHADOW_GLYPHS: Readonly<Record<string, readonly string[]>> = {']
for ch, g in out.items():
    key = "' '" if ch == " " else ("\"'\"" if ch == "'" else f'"{ch}"')
    w = width(g)
    rows = ", ".join('"' + r.ljust(w).replace("\\", "\\\\").replace('"', '\\"') + '"' for r in g)
    ts.append(f"  {key}: [{rows}],")
ts += ['};', '', '/** Typeset `text` (unknown chars are skipped); returns SHADOW_ROWS rows of equal width. */',
       'export function shadowText(text: string, gap = 0): string[] {',
       '  const rows: string[] = Array.from({ length: SHADOW_ROWS }, () => "");',
       '  for (const ch of text.toUpperCase()) {',
       '    const g = SHADOW_GLYPHS[ch];',
       '    if (!g) continue;',
       '    const w = Math.max(...g.map((r) => r.length));',
       '    for (let i = 0; i < SHADOW_ROWS; i++) rows[i] += (g[i] ?? "").padEnd(w) + " ".repeat(gap);',
       '  }',
       '  const width = Math.max(...rows.map((r) => r.length));',
       '  return rows.map((r) => r.padEnd(width));',
       '}', '',
       '/** Visible width of `shadowText(text, gap)`. */',
       'export function shadowWidth(text: string, gap = 0): number {',
       '  return shadowText(text, gap)[0]?.length ?? 0;',
       '}', '']
open(OUT, "w", encoding="utf-8").write("\n".join(ts))
print(f"wrote {OUT}: {len(out)} glyphs, height {height}")
for word in ["STAGEHAND", "EVALS", "92.1%", "ACCURACY", "SPEED", "COST"]:
    rows = [""] * height
    for ch in word:
        g = out[ch]; w = width(g)
        for i in range(height): rows[i] += g[i].ljust(w)
    print(f"\n{word}: {len(rows[0])} cols")
    print("\n".join(r.rstrip() for r in rows if r.strip()))
